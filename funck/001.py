def is_arithmetic_progression(a, b, c):
    """
    Проверяет, являются ли три числа последовательными членами арифметической прогрессии.

    Аргументы:
    a, b, c - три числа для проверки

    Возвращает:
    True - если числа являются последовательными членами арифметической прогрессии
    False - в противном случае
    """
    # В арифметической прогрессии разность между соседними членами постоянна
    # Проверяем: b - a == c - b
    return (b - a) == (c - b)

