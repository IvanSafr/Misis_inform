# ли	три	заданных	числа	(в	указанном	порядке)	последователь
# ными	членами	арифметической	прогрессии.	Процесс	отнесения
# введенных	чисел	к	определенной	группе	реализуйте	с	использо
# ванием	функции,	которая	принимает	эти	числа	в	качестве	аргу
